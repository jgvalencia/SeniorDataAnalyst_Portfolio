-- Create Dataset to be sent to Python Predictive Model

WITH base AS (
    SELECT
        t.transaction_id,
        t.customer_id,
        t.merchant_id,
        t.amount,
        t.mcc,
        t.channel,
        t.device_id,
        t.ip_address,
        t.country,
        t.transaction_timestamp,
        t.is_fraud,

        -- comportamiento del cliente
        AVG(t.amount) OVER (PARTITION BY t.customer_id) AS avg_customer_amount,
        COUNT(*) OVER (PARTITION BY t.customer_id 
                       ORDER BY t.transaction_timestamp 
                       RANGE BETWEEN INTERVAL '7' DAY PRECEDING AND CURRENT ROW) AS tx_last_7d,

        -- velocity
        COUNT(*) OVER (PARTITION BY t.customer_id 
                       ORDER BY t.transaction_timestamp 
                       RANGE BETWEEN INTERVAL '1' HOUR PRECEDING AND CURRENT ROW) AS tx_last_1h,
        COUNT(*) OVER (PARTITION BY t.customer_id 
                       ORDER BY t.transaction_timestamp 
                       RANGE BETWEEN INTERVAL '5' MINUTE PRECEDING AND CURRENT ROW) AS tx_last_5m,

        -- riesgo del merchant
        m.merchant_risk_score,
        m.chargeback_rate,

        -- riesgo del dispositivo
        d.device_change_30d,
        d.device_risk_score,

        -- geolocalización
        CASE WHEN t.country != c.home_country THEN 1 ELSE 0 END AS foreign_tx

    FROM transactions t
    LEFT JOIN merchants m ON t.merchant_id = m.merchant_id
    LEFT JOIN devices d ON t.device_id = d.device_id
    LEFT JOIN customers c ON t.customer_id = c.customer_id
)

SELECT *
FROM base;
